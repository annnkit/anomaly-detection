import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split

df = pd.read_csv("creditcard.csv")

df.shape

df.info()

df.isnull().sum()

df["Class"].value_counts()

fraud = df[df["Class"]!=0]
non_fraud = df[df["Class"]==0]

fraud.shape

non_fraud.shape

fraud["Amount"].describe()

non_fraud["Amount"].describe()

df.groupby("Class").mean()

"""It means that the mean of the samples matches that of the data grouped by class.

The Data is pretty unbalanced, so we can not train the model on it so i'm going to try resample it.
"""

non_fraud = non_fraud.sample(n=492)

new_df = pd.concat([fraud, non_fraud], axis=0)

new_df.head()

new_df.tail()

new_df["Class"].value_counts()

X = new_df.drop(columns = "Class", axis = 1)
y = new_df["Class"]

X.shape

X.head()

y.head()

y.isnull().value_counts()

clean_df = new_df.dropna()

X = clean_df.drop(columns="Class", axis=1)
y = clean_df["Class"]

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, stratify=y, random_state=2)

X_train.shape, X_test.shape, y_train.shape, y_test.shape

"""# LogReg"""

from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.linear_model import LogisticRegression

preprocesser = ColumnTransformer([
    ('std', StandardScaler(), X.columns)
])

lr_pipe = Pipeline([
    ('preprocesser', preprocesser),
    ('classifier', LogisticRegression(random_state=42, ))
])

lr_pipe.fit(X_train, y_train)

train_pred = lr_pipe.predict(X_train)
test_pred = lr_pipe.predict(X_test)

"""# Evaluation of LogReg"""

from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

print(accuracy_score(y_train, train_pred))
print(accuracy_score(y_test, test_pred))

print("training: \n", classification_report(y_train, train_pred))
print("testing: \n", classification_report(y_test, test_pred))

print("training: \n", confusion_matrix(y_train, train_pred))
print("\ntesting: \n", confusion_matrix(y_test, test_pred))

"""# Iso Forest Model"""

from sklearn.ensemble import IsolationForest

iso_pipe = Pipeline(
    [
        ("preprocessor", preprocesser),
        ("classifier", IsolationForest(n_estimators=100, contamination=0.01, random_state=42))
    ]
)

iso_pipe.fit(X_train)

iso_pred_train = iso_pipe.predict(X_train)
iso_pred_test = iso_pipe.predict(X_test)

iso_pred_train = (iso_pred_train==-1).astype(int)
iso_pred_test = (iso_pred_test==-1).astype(int)

print("training: \n", classification_report(y_train, iso_pred_train))
print("testing: \n", classification_report(y_test, iso_pred_test))

"""Since this is this model cannot ditinguish the fraudulent transactions using the features isolation forest sees, we are going to conclude that the final model is Logistic Regrssion."""

